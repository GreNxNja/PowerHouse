import { z } from "zod";

const slug = z.string().regex(/^[a-z0-9]+(?:-[a-z0-9]+)*$/, "kebab-case slug");
const time = z.string().regex(/^([01]\d|2[0-3]):[0-5]\d$/, "HH:MM, 24-hour");
/** Key into the generated image manifest, e.g. "classes/barbell-strength". */
const imageKey = z.string().regex(/^[a-z0-9/-]+$/);

export const days = [
  "monday",
  "tuesday",
  "wednesday",
  "thursday",
  "friday",
  "saturday",
  "sunday",
] as const;
export const daySchema = z.enum(days);
export type Day = z.infer<typeof daySchema>;

// ---------- Gym ----------

export const gymSchema = z.object({
  /** True while any detail below is invented. Flip to false once confirmed. */
  placeholder: z.boolean(),
  name: z.string(),
  tagline: z.string(),
  description: z.string().max(160),
  locale: z.string(),
  currency: z.string().length(3),
  phone: z.object({
    display: z.string(),
    e164: z.string().regex(/^\+\d{7,15}$/),
  }),
  whatsapp: z.string().regex(/^\d{7,15}$/, "digits only, with country code"),
  email: z.email(),
  address: z.object({
    street: z.string(),
    locality: z.string(),
    region: z.string(),
    postalCode: z.string(),
    country: z.string().length(2),
  }),
  /** Null until the real location is known. Enables the map and JSON-LD geo. */
  geo: z.object({ lat: z.number(), lng: z.number() }).nullable(),
  hours: z
    .array(
      z.object({
        days: z.array(daySchema).min(1),
        opens: time,
        closes: time,
      }),
    )
    .min(1),
  /** The building from the street, shown with the address on /contact. */
  exterior: z
    .object({
      image: imageKey,
      alt: z.string().min(1),
      caption: z.string().max(80),
    })
    .optional(),
  /** Photos of the space. The first is the large lead image. */
  gallery: z
    .array(
      z.object({
        image: imageKey,
        alt: z.string().min(1),
        caption: z.string().max(60),
      }),
    )
    .default([]),
});
export type Gym = z.infer<typeof gymSchema>;

// ---------- Classes ----------

export const classCategories = [
  "strength",
  "technique",
  "conditioning",
  "mobility",
] as const;
export const classCategorySchema = z.enum(classCategories);
export type ClassCategory = z.infer<typeof classCategorySchema>;

export const levelSchema = z.enum([
  "all",
  "beginner",
  "intermediate",
  "advanced",
]);
export type Level = z.infer<typeof levelSchema>;

export const gymClassSchema = z.object({
  slug,
  name: z.string(),
  category: classCategorySchema,
  level: levelSchema,
  durationMinutes: z.number().int().positive(),
  featured: z.boolean().default(false),
  summary: z.string().max(140),
  description: z.array(z.string()).min(1),
  whoItsFor: z.string(),
  whatToExpect: z.array(z.string()).min(2),
  image: imageKey,
  imageAlt: z.string().min(1),
  coaches: z.array(slug).min(1),
});
export type GymClass = z.infer<typeof gymClassSchema>;

// ---------- Trainers ----------

export const trainerSchema = z.object({
  slug,
  name: z.string(),
  role: z.string(),
  bio: z.array(z.string()).min(1),
  specialties: z.array(z.string()).min(1),
  certifications: z.array(z.string()),
  image: imageKey,
  imageAlt: z.string().min(1),
});
export type Trainer = z.infer<typeof trainerSchema>;

// ---------- Membership ----------

export const planSchema = z.object({
  id: slug,
  name: z.string(),
  summary: z.string(),
  /** Price per month on a monthly rolling plan. */
  monthly: z.number().positive(),
  /** Effective price per month when paid annually. */
  annualMonthly: z.number().positive(),
  highlighted: z.boolean().default(false),
  features: z.array(z.string()).min(1),
});
export type Plan = z.infer<typeof planSchema>;

export const membershipSchema = z.object({
  plans: z.array(planSchema).min(1),
  comparison: z.array(
    z.object({
      feature: z.string(),
      /** Keyed by plan id. true/false renders as a tick or dash. */
      values: z.record(z.string(), z.union([z.boolean(), z.string()])),
    }),
  ),
  notes: z.array(z.string()),
  faqs: z.array(z.object({ question: z.string(), answer: z.string() })),
});
export type Membership = z.infer<typeof membershipSchema>;

// ---------- Timetable ----------

export const sessionSchema = z.object({
  start: time,
  end: time,
  classSlug: slug,
  trainerSlug: slug,
});
export type Session = z.infer<typeof sessionSchema>;

export const timetableSchema = z.object({
  /** ISO date the timetable was last reviewed. Shown on the page. */
  updated: z.iso.date(),
  week: z.record(daySchema, z.array(sessionSchema)),
});
export type Timetable = z.infer<typeof timetableSchema>;

// ---------- Image manifest (generated by scripts/optimize-images.ts) ----------

export const imageManifestSchema = z.record(
  z.string(),
  z.object({
    width: z.number().int(),
    height: z.number().int(),
    widths: z.array(z.number().int()).min(1),
  }),
);
export type ImageManifest = z.infer<typeof imageManifestSchema>;
